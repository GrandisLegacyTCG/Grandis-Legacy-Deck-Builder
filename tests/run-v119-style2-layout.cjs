'use strict';
const fs=require('fs');
const assert=require('assert');
const css=fs.readFileSync('style-2/css/app-v1.19.css','utf8');
const html=fs.readFileSync('style-2/index.html','utf8');
const js=fs.readFileSync('style-2/js/app-v1.21.js','utf8');
assert(html.includes('app-v1.19.css?v=1.19'),'v1.19 CSS is not active');
assert(html.includes('app-v1.21.js?v=1.26'),'v1.21 JS is not active');
assert(/id="mainDeckViewDialog" class="app-dialog legacy-reference-dialog"/.test(html),'Deck View does not reuse Legacy dialog class');
assert((html.match(/class="dialog-card legacy-reference-card"/g)||[]).length>=2,'Deck View does not reuse Legacy card container class');
assert(/<div class="legacy-reference-head">[\s\S]*?Deck View/.test(html),'Deck View does not reuse Legacy header class');
assert(/id="mainDeckViewGrid" class="legacy-reference-grid"/.test(html),'Deck View does not reuse Legacy grid class');
assert(js.includes('class="legacy-reference-card-tile"'),'Deck View cards do not reuse Legacy tile class');
assert(js.includes('main-deck-view-quantity'),'Deck View quantity badge missing');
assert(js.includes('reviewButton(card.id)'),'Deck View enlarge control missing');
assert(!/data-main-deck-view-(?:add|remove)/.test(js),'Deck View must remain view-only');
assert(css.includes('grid-template-columns:repeat(4,minmax(0,1fr))!important'),'Mobile Deck Name tools are not one four-button row');
const marker='/* Deck Builder v1.19 — literal Legacy Deck Library reuse + locked mobile position columns. */';
const block=css.slice(css.lastIndexOf(marker));
assert(block.includes('.hero-slots-grid,\n  .legacy-slots-grid'),'Shared Hero/Legacy grid selector missing');
assert(block.includes('grid-template-columns:repeat(3,minmax(0,1fr))!important'),'Shared 3-column geometry missing');
assert(block.includes('.hero-slot,\n  .legacy-slot'),'Shared Hero/Legacy frame selector missing');
assert(block.includes('justify-self:stretch!important'),'Hero/Legacy frames are not hard-aligned');
assert(block.includes('.card-stage,\n  .legacy-card-stage'),'Shared card-stage selector missing');
assert(block.includes('max-width:none!important'),'Card stages are not locked to shared widths');
assert(block.includes('left:33.333333%!important') && block.includes('left:66.666667%!important'),'Swap boundaries are not aligned to shared columns');
assert(js.includes('const MAIN_DECK_LEGAL_LIMIT=60;'),'60-card legal limit changed');
assert(js.includes('const MAIN_DECK_WORKSPACE_LIMIT=80;'),'80-card workspace changed');
console.log('PASS Deck Builder v1.19 literal Legacy library reuse and mobile alignment');
